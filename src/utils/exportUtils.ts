// Zero-dependency PDF 1.4 generator for institutional examination reports
function escapePdfText(text: string): string {
  return text
    .replace(/[^\x20-\x7E]/g, ' ')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

export interface PdfReportTable {
  title: string;
  subtitle: string;
  institutionName: string;
  academicTerm: string;
  headers: string[];
  rows: string[][];
}

export function downloadReportAsPdf(report: PdfReportTable, filename: string): void {
  const pageWidth = 612;
  const pageHeight = 792;
  const margin = 42;
  const usableWidth = pageWidth - margin * 2;
  const linesPerPage = 38;

  const colCount = report.headers.length;
  const colWidth = Math.floor(usableWidth / Math.max(colCount, 1));
  const maxCharsPerCol = Math.max(8, Math.floor(colWidth / 5.4));

  const truncate = (val: string, max: number) =>
    val.length > max ? val.slice(0, max - 2) + '..' : val;

  const chunks: string[][][] = [];
  for (let i = 0; i < report.rows.length; i += linesPerPage) {
    chunks.push(report.rows.slice(i, i + linesPerPage));
  }
  if (chunks.length === 0) chunks.push([]);

  const pageContents: string[] = chunks.map((pageRows, pageIdx) => {
    const cmds: string[] = [];
    // Header navy bar
    cmds.push('0.06 0.15 0.28 rg');
    cmds.push(`${margin} ${pageHeight - 74} ${usableWidth} 36 re f`);
    cmds.push('1 1 1 rg');
    cmds.push(`BT /F2 12 Tf ${margin + 12} ${pageHeight - 52} Td (${escapePdfText(report.institutionName)}) Tj ET`);
    cmds.push(`BT /F1 8.5 Tf ${margin + 12} ${pageHeight - 66} Td (${escapePdfText(report.academicTerm)}) Tj ET`);

    // Report title
    cmds.push('0.06 0.15 0.28 rg');
    cmds.push(`BT /F2 13 Tf ${margin} ${pageHeight - 100} Td (${escapePdfText(report.title)}) Tj ET`);
    cmds.push('0.35 0.42 0.52 rg');
    cmds.push(`BT /F1 9 Tf ${margin} ${pageHeight - 115} Td (${escapePdfText(report.subtitle)} | Page ${pageIdx + 1} of ${chunks.length}) Tj ET`);

    // Table header row
    let y = pageHeight - 142;
    cmds.push('0.93 0.96 1.0 rg');
    cmds.push(`${margin} ${y - 6} ${usableWidth} 20 re f`);
    cmds.push('0.06 0.15 0.28 rg');
    report.headers.forEach((h, idx) => {
      const x = margin + 6 + idx * colWidth;
      cmds.push(`BT /F2 8.5 Tf ${x} ${y} Td (${escapePdfText(truncate(h, maxCharsPerCol))}) Tj ET`);
    });

    y -= 22;
    cmds.push('0.85 0.88 0.92 RG 0.5 w');
    cmds.push(`${margin} ${y + 14} m ${margin + usableWidth} ${y + 14} l S`);

    // Table rows
    pageRows.forEach((row, rIdx) => {
      if (rIdx % 2 === 1) {
        cmds.push('0.97 0.98 0.99 rg');
        cmds.push(`${margin} ${y - 4} ${usableWidth} 15 re f`);
      }
      cmds.push('0.12 0.16 0.24 rg');
      row.forEach((cell, idx) => {
        const x = margin + 6 + idx * colWidth;
        cmds.push(`BT /F1 8 Tf ${x} ${y} Td (${escapePdfText(truncate(cell, maxCharsPerCol))}) Tj ET`);
      });
      y -= 16;
    });

    // Footer
    cmds.push('0.45 0.52 0.62 rg');
    cmds.push(
      `BT /F1 8 Tf ${margin} 28 Td (Generated by Invigilation and Room Allocation Engine on ${escapePdfText(
        new Date().toLocaleDateString('en-US', {
          year: 'numeric',
          month: 'short',
          day: 'numeric',
        })
      )}) Tj ET`
    );

    return cmds.join('\n');
  });

  // Assemble PDF object stream
  const objects: string[] = [];
  // 1: Catalog, 2: Pages, 3: F1 Helvetica, 4: F2 Helvetica-Bold
  const pageObjStart = 5;
  const pageRefs = pageContents
    .map((_, idx) => `${pageObjStart + idx * 2} 0 R`)
    .join(' ');

  objects.push('1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj');
  objects.push(`2 0 obj\n<< /Type /Pages /Kids [${pageRefs}] /Count ${pageContents.length} >>\nendobj`);
  objects.push('3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj');
  objects.push('4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj');

  pageContents.forEach((stream, idx) => {
    const pageObjId = pageObjStart + idx * 2;
    const contentObjId = pageObjId + 1;
    objects.push(
      `${pageObjId} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentObjId} 0 R >>\nendobj`
    );
    objects.push(
      `${contentObjId} 0 obj\n<< /Length ${stream.length} >>\nstream\n${stream}\nendstream\nendobj`
    );
  });

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [0];
  for (const obj of objects) {
    offsets.push(pdf.length);
    pdf += obj + '\n';
  }
  const xrefStart = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += '0000000000 65535 f \n';
  for (let i = 1; i <= objects.length; i++) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;

  const blob = new Blob([pdf], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
